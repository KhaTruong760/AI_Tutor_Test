CREATE OR REPLACE FUNCTION "public"."enrollments_check_total_hours"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
DECLARE
	max_weekly_hours CONSTANT NUMERIC := 168;
	other_hours NUMERIC;
BEGIN
	IF NEW.status NOT IN ('active', 'paused') OR NEW.weekly_study_hours IS NULL THEN
		RETURN NEW;
	END IF;

	-- serialize concurrent writes for the same learner
	PERFORM pg_advisory_xact_lock(NEW.user_id);

	SELECT COALESCE(SUM(weekly_study_hours), 0) INTO other_hours
	FROM enrollments
	WHERE user_id = NEW.user_id
	  AND status IN ('active', 'paused')
	  AND id IS DISTINCT FROM NEW.id;

	IF other_hours + NEW.weekly_study_hours > max_weekly_hours THEN
		RAISE EXCEPTION 'Total weekly_study_hours of open enrollments (%) would exceed % for user %',
			other_hours + NEW.weekly_study_hours, max_weekly_hours, NEW.user_id
			USING ERRCODE = 'check_violation';
	END IF;

	RETURN NEW;
END;
$$;


